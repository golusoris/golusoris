set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly SCRIPT_DIR
# CHECK may name a mutated copy, to prove that these cases notice a weakened check.
readonly CHECK="${CHECK:-$SCRIPT_DIR/check-attribution.sh}"
repo="$(mktemp -d "${TMPDIR:-/tmp}/golusoris-attribution.XXXXXX")"
readonly repo
trap 'rm -rf "$repo"' EXIT

git_in() {
	git -C "$repo" -c commit.gpgSign=false "$@"
}

commit_as() {
	local name="$1" email="$2" message="$3"
	git_in -c user.name="$name" -c user.email="$email" commit -q --allow-empty -m "$message"
	git_in rev-parse HEAD
}

# expect_status WANT ARGS... runs the check with standard input passed through.
expect_status() {
	local want="$1" status=0
	shift
	(cd "$repo" && bash "$CHECK" "$@") >/dev/null 2>&1 || status=$?
	if [[ "$status" -ne "$want" ]]; then
		printf 'check-attribution.sh %s: expected exit %d, got %d\n' "$*" "$want" "$status" >&2
		exit 1
	fi
}

# message_status WANT LINE checks one signed commit message that ends with LINE.
message_status() {
	local want="$1" line="$2" status=0
	printf 'feat: x\n\nBody text.\n\nSigned-off-by: Dev <dev@example.invalid>\n%s\n' "$line" > "$repo/message"
	(cd "$repo" && bash "$CHECK" --message message) >/dev/null 2>&1 || status=$?
	if [[ "$status" -ne "$want" ]]; then
		printf 'message ending in "%s": expected exit %d, got %d\n' "$line" "$want" "$status" >&2
		exit 1
	fi
}

git_in init -q

# Refused: one case per identity group, so a group that stops matching is noticed alone.
refused_lines=(
	'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'
	'Co-authored-by: Claude <assistant@example.invalid>, Claude Code'
	'Co-authored-by: Assistant <noreply@anthropic.com>'
	'Co-authored-by: Codex <codex@example.invalid>'
	'Co-authored-by: Assistant <noreply@mail.openai.com>'
	'Co-authored-by: ChatGPT <assistant@example.invalid>'
	'Assisted-by: GPT-5 <assistant@example.invalid>'
	'Co-authored-by: Gemini <assistant@example.invalid>'
	'Generated-by: Antigravity'
	'Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>'
	'Co-authored-by: Cursor Agent <cursoragent@cursor.com>'
	'Co-authored-by: Agent <agent@cursor.com>'
	'Co-authored-by: Windsurf <assistant@example.invalid>'
	'Co-authored-by: aider (some-model) <noreply@aider.chat>'
	'Co-authored-by: Devin AI <158243242+devin-ai-integration[bot]@users.noreply.github.com>'
	'Co-authored-by: opencode <assistant@example.invalid>'
	'CO-AUTHORED-BY: COPILOT <175728472+Copilot@users.noreply.github.com>'
	'  co-authored-by: gemini <assistant@example.invalid>'
	'🤖 Generated with [Claude Code](https://claude.com/claude-code)'
	'Generated with Claude Code'
	'Generated by: Codex'
	'Created with Cursor'
	'Written by Gemini.'
)
for line in "${refused_lines[@]}"; do
	message_status 1 "$line"
done

# Accepted: people, bots that are not coding tools, generators, and prose that names a tool.
accepted_lines=(
	''
	'Co-authored-by: renovate[bot] <29139614+renovate[bot]@users.noreply.github.com>'
	'Co-authored-by: Claude Dupont <claude.dupont@example.org>'
	'Co-authored-by: Claude Coderre <claude.coderre@example.org>'
	'Co-authored-by: Devin Smith <devin.smith@example.org>'
	'Co-authored-by: Dev <dev@notanthropic.com.example.org>'
	'Generated by ogen v1.24.0.'
	'Regenerated with make gen.'
	'This describes the .claude skills, the Codex client and Copilot.'
	'# Co-authored-by: Gemini <assistant@example.invalid>'
)
for line in "${accepted_lines[@]}"; do
	message_status 0 "$line"
done

# A CRLF message is judged like an LF one.
printf 'feat: x\r\n\r\nCo-authored-by: Gemini <assistant@example.invalid>\r\n' > "$repo/crlf"
expect_status 1 --message crlf

# Range mode reads every commit of the range, a bot-authored one included.
base="$(commit_as base base@example.invalid 'base')"
clean="$(commit_as Dev dev@example.invalid "$(printf 'feat: x\n\nSigned-off-by: Dev <dev@example.invalid>')")"
expect_status 0 "$base" "$clean"
bad="$(commit_as Dev dev@example.invalid "$(printf 'feat: y\n\nCo-authored-by: Codex <codex@example.invalid>')")"
later="$(commit_as Dev dev@example.invalid 'feat: z')"
expect_status 1 "$base" "$later"
expect_status 1 "$clean" "$bad"
expect_status 0 "$bad" "$later"
bot="$(commit_as 'renovate[bot]' '29139614+renovate[bot]@users.noreply.github.com' \
	"$(printf 'chore: w\n\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>')")"
expect_status 1 "$later" "$bot"

# Text mode reads a pull request body from standard input.
printf '## Summary\n\n- A change.\n' | expect_status 0 --text
printf '## Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n' | expect_status 1 --text
expect_status 0 --text < /dev/null

# Every other argument shape is a usage error, never a pass.
expect_status 2
expect_status 2 --unknown
expect_status 2 --message
expect_status 2 --message missing-file
expect_status 2 --text extra
expect_status 2 a b c

printf 'attribution check tests passed\n'
